import { expect, test } from "bun:test";
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { execute, withFixture } from "../test-support";
import { runGit } from "../utils/git";
import { createGitShowTool } from "./git-show";
import { createGitBlameTool } from "./git-blame";
import { createDiffSummaryTool } from "./diff-summary";

test("Git inspection restricts paths, separates staged changes and blames short historical files", withFixture(async ({ cwd, outside }) => {
    await runGit(cwd, ["init"]);
    await writeFile(join(cwd, "a.ts"), "export const value = 1;\nsecond line\n");
    await writeFile(join(cwd, "b.ts"), "original\n");
    await writeFile(join(cwd, ".env"), "FAKE_PRIVATE_FIXTURE");
    await runGit(cwd, ["add", "--", "a.ts", "b.ts", ".env"]);
    await runGit(cwd, ["-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid", "commit", "-m", "initial fixture"]);
    const shown = await execute(createGitShowTool(cwd), {});
    expect(shown.text).toContain("initial fixture"); expect(shown.text).toContain("+export const value = 1;");
    expect(shown.text).not.toContain("FAKE_PRIVATE_FIXTURE");
    await writeFile(join(cwd, "a.ts"), "export const value = 2;\nsecond line\nnew line\n");
    await writeFile(join(cwd, "b.ts"), "staged\n");
    await writeFile(join(cwd, ".env"), "ANOTHER_PRIVATE_FIXTURE");
    await runGit(cwd, ["add", "--", "b.ts"]);
    const unstaged = await execute(createDiffSummaryTool(cwd), {});
    expect(unstaged.files).toEqual([{ path: "a.ts", additions: 2, deletions: 1, binary: false }]);
    const staged = await execute(createDiffSummaryTool(cwd), { staged: true });
    expect(staged.files).toEqual([{ path: "b.ts", additions: 1, deletions: 1, binary: false }]);
    await writeFile(join(outside, "ignored"), "FAKE_VALUE_MUST_NOT_LEAK");
    await runGit(cwd, ["config", "blame.ignoreRevsFile", join(outside, "ignored")]);
    await runGit(cwd, ["config", "mailmap.file", join(outside, "ignored")]);
    await expect(execute(createGitBlameTool(cwd), { path: "a.ts" })).rejects.toThrow("UNSAFE_GIT_BLAME_CONFIG");
    await runGit(cwd, ["config", "--unset-all", "blame.ignoreRevsFile"]);
    const blamed = await execute(createGitBlameTool(cwd), { path: "a.ts" });
    expect(blamed.text).toContain("author Fixture"); expect(blamed.text).toContain("\texport const value = 1;");
    expect(blamed.text).not.toContain("value = 2"); expect(blamed.text).not.toContain("FAKE_VALUE_MUST_NOT_LEAK");
    expect((await execute(createGitBlameTool(cwd), { path: "a.ts", startLine: 2, limit: 1 })).text).toContain("\tsecond line");
    await expect(execute(createGitBlameTool(cwd), { path: "a.ts", startLine: 5 })).rejects.toThrow("LINE_OUT_OF_RANGE");
    await expect(execute(createGitShowTool(cwd), { path: ".env" })).rejects.toThrow();
    await expect(execute(createGitBlameTool(cwd), { path: ".env" })).rejects.toThrow();
    await expect(execute(createDiffSummaryTool(cwd), { path: "../outside" })).rejects.toThrow();
    await expect(execute(createGitShowTool(cwd), { revision: "--output=unsafe" })).rejects.toThrow();
    const controller = new AbortController(); controller.abort(new Error("fixture cancelled"));
    await expect(execute(createGitShowTool(cwd), {}, controller.signal)).rejects.toThrow("fixture cancelled");
    await expect(execute(createDiffSummaryTool(cwd), {}, controller.signal)).rejects.toThrow("fixture cancelled");
    expect((await runGit(cwd, ["diff", "--cached", "--name-only"])).stdout.trim()).toBe("b.ts");
}), 60_000);
